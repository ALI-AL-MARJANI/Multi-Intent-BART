#!/usr/bin/env python3
"""Copy the generated result tables into the README.

    python scripts/aggregate_results.py && python scripts/make_figures.py
    python scripts/update_readme.py

Replaces the text between ``<!-- TLDR:BEGIN -->`` / ``<!-- TLDR:END -->`` and
between ``<!-- RESULTS:BEGIN -->`` / ``<!-- RESULTS:END -->``. Every number
written comes from ``results/nlu/summary.json`` or ``results/ood/summary.json``;
the text outside the markers is not touched.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path
from typing import Any

from gemis.utils.io import read_json

TBD = "TBD (run pending)"
NLU_METRICS = (("slot_f1", "Slot F1"), ("intent_accuracy", "Intent acc."), ("overall_accuracy", "Overall acc."))


def fmt(stat: dict[str, Any], digits: int = 2) -> str:
    if stat["std"] is None:
        return f"{stat['mean']:.{digits}f} (1 seed)"
    return f"{stat['mean']:.{digits}f} ± {stat['std']:.{digits}f}"


def replace_block(text: str, name: str, body: str) -> str:
    pattern = re.compile(rf"(<!-- {name}:BEGIN -->\n).*?(<!-- {name}:END -->)", re.DOTALL)
    if not pattern.search(text):
        raise ValueError(f"README has no {name} markers")
    return pattern.sub(lambda m: m.group(1) + body.rstrip("\n") + "\n" + m.group(2), text)


def strip_header(markdown: str) -> str:
    """Drop the 'generated by' comment line of a summary file."""
    lines = [line for line in markdown.splitlines() if not line.startswith("<!-- generated")]
    return "\n".join(lines).strip("\n")


def tldr(results: Path) -> str:
    nlu = read_json(results / "nlu" / "summary.json")["experiments"]
    ood = read_json(results / "ood" / "summary.json")["experiments"]
    done = [row for row in nlu if row["ours"]]
    if not done:
        return TBD

    lines = [
        "Test-set results of this repository (*ours*, mean ± standard deviation over seeds) next to the numbers "
        "published by Li & Zhu (2026) (*paper*, number of runs not reported).",
        "",
        "| Experiment | Seeds | " + " | ".join(f"{label} (ours) | Paper" for _, label in NLU_METRICS) + " |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for row in done:
        cells = [f"`{row['experiment']}`", str(len(row["seeds"]))]
        for key, _ in NLU_METRICS:
            cells += [fmt(row["ours"][key]), f"{row['paper'][key]:.1f}" if row["paper"] else "n/a"]
        lines.append("| " + " | ".join(cells) + " |")

    for exp in ood:
        for ood_set, scores in exp["detection"].items():
            lines += [
                "",
                f"OOD detection, `{exp['experiment']}`, `{ood_set}` (n={exp['set_sizes'][ood_set]}) against the "
                f"in-distribution test split (n={exp['set_sizes']['id_test']}), {len(exp['seeds'])} seed(s). "
                "False-alarm rate of the conformal threshold at alpha = 0.05 (target: at most 0.05).",
                "",
                "| Score | AUROC ↑ | FPR@95TPR ↓ | False alarms, threshold from random halves of test "
                "| False alarms, threshold from dev |",
                "|---|---|---|---|---|",
            ]
            for score, m in scores.items():
                c = exp["conformal"][score]["0.05"]
                lines.append(
                    f"| `{score}` | {fmt(m['auroc'], 4)} | {fmt(m['fpr_at_95tpr'], 4)} "
                    f"| {fmt(c['fpr_test_split'], 4)} | {fmt(c['fpr_dev_calibrated'], 4)} |"
                )

    run = read_json(done[0]["source_files"][0])
    env = run["env"]
    seeds = ", ".join(str(s) for s in sorted({s for row in done for s in row["seeds"]}))
    lines += [
        "",
        f"Setup: {env['platform']}, {env['memory_gb']} GB, device `{env['device']}`, torch "
        f"{env['versions']['torch']}, transformers {env['versions']['transformers']}; official MixATIS split "
        f"(test n={done[0]['n_test']}); seeds {seeds}; greedy decoding. Sources: "
        "[`results/nlu/summary.json`](results/nlu/summary.json), "
        "[`results/ood/summary.json`](results/ood/summary.json). Runs that are configured but not done are "
        f"listed as `{TBD}` in [Results](#results).",
    ]
    return "\n".join(lines)


def results_section(results: Path) -> str:
    parts = [
        "### Part 1: reproduction of the NLU results",
        "",
        "Source: [`results/nlu/summary.md`](results/nlu/summary.md), built by `scripts/aggregate_results.py` "
        "from the per-seed files in `results/nlu/<experiment>/`.",
        "",
        strip_header((results / "nlu" / "summary.md").read_text(encoding="utf-8")),
    ]
    for figure in sorted((results / "figures").glob("training_*.png")):
        parts += ["", f"![training curves]({figure.as_posix()})"]
    parts += [
        "",
        "### Part 2: OOD detection and conformal calibration",
        "",
        "Source: [`results/ood/summary.md`](results/ood/summary.md), built from "
        "`results/ood/<experiment>/seed*/metrics.json`; per-utterance scores are in the `scores.csv` files "
        "next to them.",
        "",
        strip_header((results / "ood" / "summary.md").read_text(encoding="utf-8")),
    ]
    for prefix in ("ood_roc", "ood_scores", "conformal_validity"):
        figures = sorted((results / "figures").glob(f"{prefix}_*.png"))
        if figures:  # one seed is shown; the other seeds are in results/figures
            parts += ["", f"![{prefix.replace('_', ' ')}]({figures[0].as_posix()})"]
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--readme", type=Path, default=Path("README.md"))
    parser.add_argument("--results", type=Path, default=Path("results"))
    args = parser.parse_args()

    text = args.readme.read_text(encoding="utf-8")
    text = replace_block(text, "TLDR", tldr(args.results))
    text = replace_block(text, "RESULTS", results_section(args.results))
    args.readme.write_text(text, encoding="utf-8")
    print(f"updated {args.readme}")


if __name__ == "__main__":
    main()
